// Package clihelp renders side-effect-free command help and its reference manual.
package clihelp

import (
	"fmt"
	"io"
	"strings"
)

//go:generate go run ./cmd/generate

type Option struct {
	Name, Value, Default, Description string
}

type Command struct {
	Name, Summary, Usage string
	Options              []Option
	Notes, Examples      []string
	Children             []Command
	Advanced             bool
}

func (c Command) child(name string) (Command, bool) {
	for _, child := range c.Children {
		if child.Name == name {
			return child, true
		}
	}
	return Command{}, false
}

// Handle runs before command dispatch, configuration reads and integration setup.
// Option values and tokens after -- are never interpreted as help requests.
// It does not validate or change the parsing of ordinary command invocations.
func Handle(root Command, args []string, stdout, stderr io.Writer) (bool, int) {
	if len(args) == 0 {
		return false, 0
	}
	explicit := args[0] == "help"
	if explicit {
		args = args[1:]
	}
	command, path := root, root.Name
	var options []Option
	var notes, examples []string
	wanted, invalid := explicit, ""
	positional := false
	for i := 0; i < len(args); i++ {
		arg := args[i]
		if arg == "--" {
			break
		}
		if arg == "--help" || arg == "-h" {
			wanted = true
			continue
		}
		if strings.HasPrefix(arg, "-") {
			name, _, assigned := strings.Cut(strings.TrimLeft(arg, "-"), "=")
			for _, option := range options {
				if name == option.Name && option.Value != "" && !assigned && i+1 < len(args) {
					i++
					break
				}
			}
			continue
		}
		if !positional {
			if child, ok := command.child(arg); ok {
				command, path = child, path+" "+arg
				options = append(options, child.Options...)
				notes = append(notes, child.Notes...)
				if len(child.Examples) > 0 {
					examples = child.Examples
				}
				continue
			}
		}
		if len(command.Children) > 0 || explicit {
			invalid = arg
		}
		positional = true
	}
	if !wanted {
		return false, 0
	}
	if invalid != "" {
		fmt.Fprintf(stderr, "Unknown help topic %q. Run `%s --help` for commands.\n", invalid, root.Name)
		return true, 2
	}
	if path != root.Name {
		command.Notes, command.Examples = notes, examples
	}
	Write(stdout, command, path, options)
	return true, 0
}

func Write(output io.Writer, command Command, path string, options []Option) {
	fmt.Fprintf(output, "%s\n\nUsage: %s", command.Summary, path)
	if command.Usage != "" {
		fmt.Fprint(output, " "+command.Usage)
	}
	fmt.Fprintln(output)
	for _, advanced := range []bool{false, true} {
		heading := false
		for _, child := range command.Children {
			if child.Advanced != advanced {
				continue
			}
			if !heading {
				label := "Commands"
				if advanced {
					label = "Advanced / integration commands"
				}
				fmt.Fprintf(output, "\n%s:\n", label)
				heading = true
			}
			fmt.Fprintf(output, "  %-20s %s\n", child.Name, child.Summary)
		}
	}
	fmt.Fprintln(output, "\nOptions:")
	for _, option := range options {
		name := "--" + option.Name
		if option.Value != "" {
			name += " " + option.Value
		}
		fmt.Fprintf(output, "  %-25s %s", name, option.Description)
		if option.Default != "" {
			fmt.Fprintf(output, " (default: %s)", option.Default)
		}
		fmt.Fprintln(output)
	}
	fmt.Fprintln(output, "  -h, --help                Show help without running the command")
	for _, note := range command.Notes {
		fmt.Fprintln(output, "\n"+note)
	}
	if len(command.Examples) > 0 {
		fmt.Fprintln(output, "\nExamples:")
		for _, example := range command.Examples {
			fmt.Fprintln(output, "  "+example)
		}
	}
	if len(command.Children) > 0 {
		fmt.Fprintf(output, "\nUse `%s <command> --help` for parameters and examples.\n", path)
	}
}

// Manual uses exactly the same descriptions, defaults and examples as the CLI.
func Manual(advanced bool) string {
	var out strings.Builder
	title := "Command reference / 命令与参数"
	if advanced {
		title = "Integration commands / 集成与调试命令"
	}
	fmt.Fprintf(&out, "# %s\n\n<!-- Generated by go generate ./packages/clihelp; edit the Go catalog. -->\n\n", title)
	if advanced {
		out.WriteString("These commands are used by integrations and isolated development workflows. Normal collaboration uses `connect` and the managed Runtime.\n\n这些入口用于集成和隔离调试，日常协作无需手动调用。以下预算与模型参数仅适用于显式调试命令，不是普通用户配置项。\n\n[User commands](cli.md).\n")
	} else {
		out.WriteString("Use `coconet --help`, `coconet help connect` or `coconet history preview --help`. All commands accept `--help` or `-h`; `coconet help` shows the overview. The server supports the same help forms. Runtime help needs no login or connected folder, writes to stdout, exits successfully and does not run the selected operation. Unknown topics exit with status 2.\n\nREADME 保留快速上手说明；本页列出公开命令、参数、默认值、适用条件和示例。Runtime 帮助无需登录或连接项目，不调用 Agent、不访问服务器，也不修改本地状态。命令行说明使用英文。首次通过 npm 启动时，启动器会安装缺失的 Runtime，或升级到用户已安装的较新 npm 包版本，然后继续原命令；不会自动降级。也可运行 `coconet update` 一次更新 npm 与 Runtime。\n\nPut flags after the command/subcommand. Required positional arguments such as `agent add claude` precede flags. Most commands accept `--flag VALUE` or `--flag=VALUE`; boolean flags may use `--flag=false`. The small `health` and `mcp` entry points accept only the exact option forms shown in their usage. `--` ends option parsing. Paths containing spaces must be quoted. Replace example IDs and paths with your own. Group option tables state which subcommands use each parameter; a parameter is not global.\n\n普通工作流沿用 Agent 的默认模型，无需设置模型或调用次数。服务端 OAuth、对象存储和容量策略使用环境变量，见 [self-hosting](../deploy/README.md)；它们不是 CLI 参数。[集成与调试命令](cli-internal.md) 单独列出。\n")
	}
	for _, root := range []Command{Runtime(), Server()} {
		if advanced && root.Name != "coconet" {
			continue
		}
		fmt.Fprintf(&out, "\n## %s\n", root.Name)
		out.WriteString("\n| Command | Purpose |\n|---|---|\n")
		for _, child := range root.Children {
			if child.Advanced == advanced {
				fmt.Fprintf(&out, "| [%s](#%s-%s) | %s |\n", child.Name, root.Name, child.Name, child.Summary)
			}
		}
		var walk func(Command, string, int)
		walk = func(c Command, path string, level int) {
			fmt.Fprintf(&out, "\n%s `%s`\n\n%s\n\n```sh\n%s", strings.Repeat("#", level), path, c.Summary, path)
			if c.Usage != "" {
				out.WriteString(" " + c.Usage)
			}
			out.WriteString("\n```\n")
			if len(c.Options) > 0 {
				out.WriteString("\n| Option | Default | Meaning |\n|---|---|---|\n")
				for _, o := range c.Options {
					name := "--" + o.Name
					if o.Value != "" {
						name += " " + o.Value
					}
					def := o.Default
					if def == "" {
						def = "—"
					}
					fmt.Fprintf(&out, "| `%s` | %s | %s |\n", strings.ReplaceAll(name, "|", "\\|"), def, strings.ReplaceAll(o.Description, "|", "\\|"))
				}
			}
			for _, note := range c.Notes {
				fmt.Fprintf(&out, "\n%s\n", note)
			}
			if len(c.Examples) > 0 {
				fmt.Fprintf(&out, "\n```sh\n%s\n```\n", strings.Join(c.Examples, "\n"))
			}
			for _, child := range c.Children {
				walk(child, path+" "+child.Name, level+1)
			}
		}
		for _, child := range root.Children {
			if child.Advanced == advanced {
				walk(child, root.Name+" "+child.Name, 3)
			}
		}
	}
	return out.String()
}

func option(name, value, def, description string) Option {
	return Option{name, value, def, description}
}

func boolean(name, description string) Option {
	return option(name, "", "false", description)
}

func leaf(name, summary, usage string, notes ...string) Command {
	return Command{Name: name, Summary: summary, Usage: usage, Notes: notes}
}
