export const languageStorageKey = 'coconet.dashboard.language';
export function detectLanguage(saved, preferred = []) {
  if (saved === 'zh' || saved === 'en') return saved;
  for (const locale of preferred) {
    if (/^zh(?:-|$)/i.test(locale)) return 'zh';
    if (/^en(?:-|$)/i.test(locale)) return 'en';
  }
  return 'en';
}
export function translate(language, key, values = {}) {
  const pair = messages[key];
  if (!pair) throw new Error('Unknown interface message: ' + key);
  return pair[language === 'zh' ? 0 : 1].replace(/\{(\w+)\}/g, (match, name) => values[name] ?? match);
}
export function errorKey(error) {
  return [error?.code, error?.message, error?.name].find(key => Object.hasOwn(messages, key)) || 'error_generic';
}

// Translate only curated system explanations; retain custom/source text verbatim.
const explanationKeys = new Map(Object.entries(messages).filter(([key]) => key.startsWith('explanation_')).flatMap(([key, pair]) => pair.map(text => [text, key])));
export function localizeFailureExplanation(explanation, t) {
  return Object.fromEntries(Object.entries(explanation || {}).map(([field, text]) => [field, explanationKeys.has(text) ? t(explanationKeys.get(text)) : text]));
}
